#!/usr/bin/env node
// Writes application/json/lib/json-schema-unicode-letter.zig: the code point
// ranges of Unicode General_Category=Letter (\p{L}, \p{Letter}) as Node's
// ECMAScript regex engine sees them. JSON Schema patterns are ECMA-262 regular
// expressions, so the validator matches what JavaScript validators match.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "application/json/lib/json-schema-unicode-letter.zig");
const letter = /^\p{L}$/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x110000; cp++) {
  const isLetter = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && letter.test(String.fromCodePoint(cp));
  if (isLetter && start < 0) start = cp;
  if (!isLetter && start >= 0) {
    ranges.push([start, cp - 1]);
    start = -1;
  }
}
const hex = (n) => "0x" + n.toString(16).toUpperCase();
const lines = [
  "// Generated by tools/gen-unicode-letter-ranges.mjs from Node " + process.version + " (Unicode " + process.versions.unicode + ").",
  "// Unicode General_Category=Letter as sorted, inclusive code point ranges.",
  "pub const ranges = [_][2]u21{",
  ...ranges.map(([a, b]) => `    .{ ${hex(a)}, ${hex(b)} },`),
  "};",
  "",
  "// Only packed is kept in the Wasm: each range as 16-bit offsets within its",
  "// 64K plane, grouped by plane, which halves the table. No range crosses a",
  "// plane and letters stop before plane 4.",
  "const plane_count = 4;",
  "const Packed = struct { ranges: [ranges.len][2]u16, starts: [plane_count + 1]usize };",
  "const packed_ranges: Packed = blk: {",
  "    var p: Packed = undefined;",
  "    var plane: usize = 0;",
  "    p.starts[0] = 0;",
  "    for (ranges, 0..) |r, i| {",
  "        if (r[0] >> 16 != r[1] >> 16 or r[1] >> 16 >= plane_count) @compileError(\"letter range crosses a plane\");",
  "        while (plane < r[0] >> 16) {",
  "            plane += 1;",
  "            p.starts[plane] = i;",
  "        }",
  "        p.ranges[i] = .{ @truncate(r[0]), @truncate(r[1]) };",
  "    }",
  "    while (plane < plane_count) {",
  "        plane += 1;",
  "        p.starts[plane] = ranges.len;",
  "    }",
  "    break :blk p;",
  "};",
  "",
  "pub fn isLetter(cp: u21) bool {",
  "    const plane = cp >> 16;",
  "    if (plane >= plane_count) return false;",
  "    const low: u16 = @truncate(cp);",
  "    var lo = packed_ranges.starts[plane];",
  "    var hi = packed_ranges.starts[plane + 1];",
  "    while (lo < hi) {",
  "        const mid = lo + (hi - lo) / 2;",
  "        if (low < packed_ranges.ranges[mid][0]) {",
  "            hi = mid;",
  "        } else if (low > packed_ranges.ranges[mid][1]) {",
  "            lo = mid + 1;",
  "        } else return true;",
  "    }",
  "    return false;",
  "}",
  "",
  "// The i-th range, read from the packed table, for code that expands",
  "// \\p{Letter} into a class without keeping the u21 table.",
  "pub fn range(i: usize) [2]u21 {",
  "    var plane: u21 = 0;",
  "    while (i >= packed_ranges.starts[plane + 1]) plane += 1;",
  "    const r = packed_ranges.ranges[i];",
  "    return .{ plane << 16 | r[0], plane << 16 | r[1] };",
  "}",
  "",
  "",
  "test \"packed lookup matches the ranges for every code point\" {",
  "    var i: usize = 0;",
  "    var cp: u32 = 0;",
  "    while (cp < 0x110000) : (cp += 1) {",
  "        while (i < ranges.len and ranges[i][1] < cp) i += 1;",
  "        const expected = i < ranges.len and ranges[i][0] <= cp;",
  "        try @import(\"std\").testing.expectEqual(expected, isLetter(@intCast(cp)));",
  "    }",
  "    for (ranges, 0..) |r, k| try @import(\"std\").testing.expectEqual(r, range(k));",
  "}",
  "",
];
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(root, out)} (${ranges.length} ranges)`);
