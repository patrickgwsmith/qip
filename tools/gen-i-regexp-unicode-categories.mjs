#!/usr/bin/env node
// Writes text/lib/i-regexp-unicode-categories.zig: the Unicode General_Category
// of every code point as runs, for the \p{..} and \P{..} escapes of I-Regexp
// (RFC 9485). Categories come from Node's regex engine, so the table follows
// the Unicode version of the Node that runs this script.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "text/lib/i-regexp-unicode-categories.zig");

// The order is the Category enum in the generated file. Cs is last: no
// I-Regexp escape names it, and surrogates never occur in UTF-8 text.
const categories = [
  "Lu", "Ll", "Lt", "Lm", "Lo",
  "Mn", "Mc", "Me",
  "Nd", "Nl", "No",
  "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
  "Zs", "Zl", "Zp",
  "Sm", "Sc", "Sk", "So",
  "Cc", "Cf", "Co", "Cn", "Cs",
];
const tests = categories.map((name) => new RegExp(`^\\p{gc=${name}}$`, "u"));

function categoryOf(cp) {
  if (cp >= 0xd800 && cp <= 0xdfff) return categories.length - 1;
  const s = String.fromCodePoint(cp);
  for (let i = 0; i < tests.length - 1; i++) if (tests[i].test(s)) return i;
  throw new Error(`no category for U+${cp.toString(16)}`);
}

// Each run is (first code point << 5) | category and lasts until the next run.
const runs = [];
let previous = -1;
for (let cp = 0; cp < 0x110000; cp++) {
  const category = categoryOf(cp);
  if (category !== previous) runs.push(cp * 32 + category);
  previous = category;
}

const hex = (n) => "0x" + n.toString(16).toUpperCase();
const rows = [];
for (let i = 0; i < runs.length; i += 8) rows.push("    " + runs.slice(i, i + 8).map(hex).join(", ") + ",");
const lines = [
  `// Generated by tools/gen-i-regexp-unicode-categories.mjs from Node ${process.version} (Unicode ${process.versions.unicode}).`,
  "// Unicode General_Category of every code point from U+0000 to U+10FFFF.",
  "",
  "pub const unicode_version = \"" + process.versions.unicode + "\";",
  "",
  "pub const Category = enum(u5) { " + categories.map((c) => c.toLowerCase()).join(", ") + " };",
  "",
  "// Each run is (first code point << 5) | category and lasts until the next",
  "// run starts; the last run lasts to U+10FFFF.",
  "pub const runs = [_]u32{",
  ...rows,
  "};",
  "",
  "test \"runs start at U+0000 and increase\" {",
  "    const std = @import(\"std\");",
  "    try std.testing.expectEqual(@as(u32, 0), runs[0] >> 5);",
  "    for (runs[1..], runs[0 .. runs.len - 1]) |run, prior| {",
  "        try std.testing.expect(run >> 5 > prior >> 5);",
  "        try std.testing.expect(run & 31 != prior & 31);",
  "    }",
  "}",
  "",
];
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(root, out)} (${runs.length} runs)`);
