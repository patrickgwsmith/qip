#!/usr/bin/env python3
"""Generate the BCP 47 subtag tables from a pinned IANA registry download.

Download the URL below and pass the file. The source hash guards against
silently changing the generated data; update it with the registry snapshot.
"""

import hashlib
from pathlib import Path
import sys

REGISTRY_URL = "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry"
REGISTRY_SHA256 = "755fad43283be7b41ebe3c89ad054b6eaf928f404f9c0edb74799e0eab74beb1"
OUTPUT = Path(__file__).resolve().parents[1] / "text/lib/bcp47-registry.zig"

# RFC 5646 section 2.2.8 closes the grandfathered list.
GRANDFATHERED = {
    "art-lojban", "cel-gaulish", "en-gb-oed", "i-ami", "i-bnn", "i-default",
    "i-enochian", "i-hak", "i-klingon", "i-lux", "i-mingo", "i-navajo",
    "i-pwn", "i-tao", "i-tay", "i-tsu", "no-bok", "no-nyn", "sgn-be-fr",
    "sgn-be-nl", "sgn-ch-de", "zh-guoyu", "zh-hakka", "zh-min", "zh-min-nan",
    "zh-xiang",
}


def checked_text(path):
    data = Path(path).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != REGISTRY_SHA256:
        raise ValueError(f"{path}: SHA-256 {digest} does not match {REGISTRY_SHA256}")
    return data.decode("utf-8")


def records(text):
    for block in text.split("\n%%\n"):
        fields = {}
        key = None
        for line in block.splitlines():
            if line.startswith(" ") and key:
                continue  # Continuation of a folded field such as Comments.
            key, _, value = line.partition(":")
            fields.setdefault(key, value.strip())
        yield fields


def expand(subtag):
    # Ranges such as qaa..qtz vary only in the trailing letters.
    low, sep, high = subtag.lower().partition("..")
    if not sep:
        return [low]
    if len(low) != len(high) or not (low + high).isalpha():
        raise ValueError(f"unexpected range {subtag}")
    out = []
    value = low
    while True:
        out.append(value)
        if value == high:
            return out
        chars = list(value)
        i = len(chars) - 1
        while chars[i] == "z":
            chars[i] = "a"
            i -= 1
        chars[i] = chr(ord(chars[i]) + 1)
        value = "".join(chars)


def alpha_index(s):
    n = 0
    for c in s:
        n = n * 26 + ord(c) - ord("a")
    return n


def language_bit(s):
    return alpha_index(s) if len(s) == 2 else 26 * 26 + alpha_index(s)


def region_bit(s):
    return alpha_index(s) if s.isalpha() else 26 * 26 + int(s)


def packed(s):
    n = 0
    for c in s:
        n = (n << 8) | ord(c)
    return n


def bitset(bits, size):
    words = [0] * ((size + 63) // 64)
    for bit in bits:
        words[bit // 64] |= 1 << (bit % 64)
    return words


def zig_array(name, kind, values, per_line):
    lines = [f"pub const {name} = [_]{kind}{{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + " ".join(f"0x{v:x}," for v in values[i:i + per_line]))
    lines.append("};")
    return lines


def main(path):
    text = checked_text(path)
    file_date = text.splitlines()[0].removeprefix("File-Date: ")
    subtags = {"language": set(), "extlang": set(), "script": set(), "region": set(), "variant": set()}
    grandfathered = set()
    for fields in records(text):
        kind = fields.get("Type")
        if kind in subtags:
            subtags[kind].update(expand(fields["Subtag"]))
        elif kind == "grandfathered":
            grandfathered.add(fields["Tag"].lower())
        elif kind not in (None, "redundant"):
            raise ValueError(f"unknown record type {kind}")
    if grandfathered != GRANDFATHERED:
        raise ValueError(f"grandfathered tags changed: {grandfathered ^ GRANDFATHERED}")

    # The grammar admits 4-8 letter languages, but none are registered. The
    # bitset covers only 2-3 letters, so stop if that changes.
    if any(not 2 <= len(s) <= 3 or not s.isalpha() for s in subtags["language"]):
        raise ValueError("unexpected language shape")
    if any(len(s) != 3 or not s.isalpha() for s in subtags["extlang"]):
        raise ValueError("unexpected extlang shape")
    if any(len(s) != 4 or not s.isalpha() for s in subtags["script"]):
        raise ValueError("unexpected script shape")
    if any(not (len(s) == 2 and s.isalpha() or len(s) == 3 and s.isdigit()) for s in subtags["region"]):
        raise ValueError("unexpected region shape")
    if any(not 4 <= len(s) <= 8 or not s.isalnum() for s in subtags["variant"]):
        raise ValueError("unexpected variant or long language shape")

    language_bits = 26 * 26 + 26 * 26 * 26
    region_bits = 26 * 26 + 1000
    output = [
        "// Generated by tools/generate-bcp47-registry-zig.py. Do not edit by hand.",
        f"// Source: {REGISTRY_URL}",
        f"// SHA-256: {REGISTRY_SHA256}",
        "// Subtags are lowercase. Private-use ranges are expanded.",
        f'pub const file_date = "{file_date}";',
        "",
        "// Bit i is set for a registered 2-letter (i < 676) or 3-letter language.",
        f"pub const language_bit_count = {language_bits};",
        *zig_array("language_bits", "u64", bitset(map(language_bit, subtags["language"]), language_bits), 4),
        "",
        "// Sorted big-endian packed subtags for binary search.",
        *zig_array("extlangs", "u32", sorted(map(packed, subtags["extlang"])), 6),
        "",
        *zig_array("scripts", "u32", sorted(map(packed, subtags["script"])), 6),
        "",
        *zig_array("variants", "u64", sorted(map(packed, subtags["variant"])), 4),
        "",
        "// Bit i is set for a registered 2-letter (i < 676) or 3-digit region.",
        f"pub const region_bit_count = {region_bits};",
        *zig_array("region_bits", "u64", bitset(map(region_bit, subtags["region"]), region_bits), 4),
        "",
    ]
    OUTPUT.write_text("\n".join(output))
    counts = ", ".join(f"{len(v)} {k}" for k, v in subtags.items())
    print(f"wrote {counts} subtags from registry {file_date} to {OUTPUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(f"usage: {sys.argv[0]} language-subtag-registry")
    main(sys.argv[1])
