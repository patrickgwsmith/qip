#!/usr/bin/env python3
"""Generate a pinned offline Can I Email feature table from caniemail.com's api/data.json."""

import hashlib
from html import unescape
import json
from pathlib import Path
import re
import sys

SOURCE_URL = "https://www.caniemail.com/api/data.json"
SOURCE_SHA256 = "7328f873fae3bb24455d10bf3005464b2af12cbbcc5b54da51683d4911235628"
OUTPUT = Path(__file__).resolve().parents[1] / "tui/lib/caniemail-data.zig"
SUMMARY_FAMILIES = ("apple-mail", "gmail", "outlook", "yahoo")
STATUS = {"y": "Supported", "a": "Partial", "n": "No", "u": "Unknown"}


def plain(value):
    if not value:
        return ""
    value = re.sub(r"\[([^]]+)\]\([^)]+\)", r"\1", value)
    # Backticked code such as `<table>` names a tag; keep it while removing real markup.
    parts = value.split("`")
    value = "".join(part if i % 2 else re.sub(r"<[^>]*>", " ", part) for i, part in enumerate(parts))
    return " ".join(unescape(value).split())


def zig_string(value):
    if any(ord(char) < 32 and char != "\n" for char in value):
        raise ValueError(f"control character in {value!r}")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def status_text(value):
    parts = value.split()
    notes = [part for part in parts[1:] if part.startswith("#")]
    if len(notes) != len(parts) - 1:
        raise ValueError(f"unexpected support value {value!r}")
    return STATUS[parts[0]] + (" (" + ", ".join(notes) + ")" if notes else "")


def summary_text(platforms, names):
    """Group each platform's latest tested status, e.g. "Supported on macOS, iOS; No on Windows"."""
    groups = {}
    for platform, versions in platforms.items():
        groups.setdefault(status_text(list(versions.values())[-1]), []).append(names[platform])
    if len(groups) == 1:
        return next(iter(groups))
    return "; ".join(f"{status} on {', '.join(platforms)}" for status, platforms in groups.items())


def platform_history(versions):
    # caniemail lists versions in test order; client version schemes differ, so keep that order.
    entries = list(versions.items())
    spans = []
    start, last, state = entries[0][0], entries[0][0], entries[0][1]
    for version, value in entries[1:]:
        if value != state:
            spans.append(f"{start}" + (f"–{last}" if last != start else "") + f": {status_text(state)}")
            start, state = version, value
        last = version
    spans.append(f"{start}" + (f"–{last}" if last != start else "") + f": {status_text(state)}")
    return "; ".join(spans)


def family_details(feature, family, names):
    platforms = feature["stats"][family]
    lines = [names["family"][family]]
    for platform, versions in platforms.items():
        lines.append(f"{names['platform'][platform]}: {platform_history(versions)}.")
    note_ids = sorted({int(part[1:]) for versions in platforms.values() for value in versions.values()
                       for part in value.split()[1:]})
    # A few source entries cite note numbers that the feature does not define.
    notes = feature["notes_by_num"] or {}
    lines.extend(f"#{number}: {plain(notes.get(str(number))) or 'Not given in the source data.'}" for number in note_ids)
    return "\n".join(lines)


def main(source):
    payload = Path(source).read_bytes()
    digest = hashlib.sha256(payload).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"unexpected caniemail data SHA-256: {digest}")
    data = json.loads(payload)
    names = data["nicenames"]
    features = data["data"]
    if len(features) != 308:
        raise ValueError(f"unexpected feature count: {len(features)}")
    date = data["last_update_date"][:10]
    output = [
        "// Generated by tools/generate-caniemail-tui-data.py. Do not edit by hand.",
        f"// Source: {SOURCE_URL} (API {data['api_version']})",
        f"// SHA-256: {SOURCE_SHA256}",
        "// License: MIT. Data from caniemail.com, (c) 2019 Remi Parmentier.",
        f"// Dataset updated: {date}",
        f"pub const snapshot = {zig_string(date)};",
        "pub const Feature = struct {",
        "    slug: []const u8,",
        "    title: []const u8,",
        "    category: []const u8,",
        "    search: []const u8,",
        "    description: []const u8,",
        "    notes: []const u8,",
        "    tested: []const u8,",
        "    summary: [4][]const u8,",
        "    clients: []const u8,",
        "};",
        "",
        "pub const features = [_]Feature{",
    ]
    for feature in sorted(features, key=lambda entry: entry["title"].lower()):
        stats = feature["stats"]
        summary = [summary_text(stats[family], names["platform"]) if family in stats else "Not tested"
                   for family in SUMMARY_FAMILIES]
        families = list(SUMMARY_FAMILIES) + sorted((family for family in stats if family not in SUMMARY_FAMILIES),
                                                   key=lambda family: names["family"][family].lower())
        clients = "\n".join(family_details(feature, family, names) for family in families if family in stats)
        category = names["category"][feature["category"]]
        search = " ".join((feature["title"], feature["slug"], feature.get("keywords") or "",
                           " ".join(feature.get("tags") or []), category))
        fields = {
            "slug": feature["slug"],
            "title": plain(feature["title"]),
            "category": category,
            "search": plain(search),
            "description": plain(feature["description"]),
            "notes": plain(feature["notes"]),
            "tested": feature["last_test_date"] or "",
        }
        output.append("    .{ " + ", ".join(f".{key} = {zig_string(value)}" for key, value in fields.items()) +
                      ", .summary = .{ " + ", ".join(map(zig_string, summary)) + " }, .clients = " +
                      zig_string(clients) + " },")
    output.extend(("};", ""))
    OUTPUT.write_text("\n".join(output))
    print(f"wrote {len(features)} features to {OUTPUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(f"usage: {sys.argv[0]} data.json")
    main(sys.argv[1])
