fn shortcodeNameEqual(input: []const u8, name: []const u8) bool {
    if (input.len != name.len) return false;
    var i: usize = 0;
    while (i < input.len) : (i += 1) {
        if (input[i] != name[i]) return false;
    }
    return true;
}

fn lookupEmoji(name: []const u8) ?[]const u8 {
    if (name.len == 0) return null;
    const range = shortcodeRange(name[0]);
    var i = range.start;
    while (i < range.end) : (i += 1) {
        const entry = EmojiEntries[i];
        if (shortcodeNameEqual(name, entry.name)) return entry.emoji;
    }
    return null;
}

const Writer = struct {
    buf: []u8,
    idx: usize,

    fn init(buf: []u8) Writer {
        return .{ .buf = buf, .idx = 0 };
    }

    fn writeByte(self: *Writer, b: u8) void {
        if (self.idx >= self.buf.len) {
            @trap();
        }
        self.buf[self.idx] = b;
        self.idx += 1;
    }

    fn writeSlice(self: *Writer, s: []const u8) void {
        if (self.idx + s.len > self.buf.len) {
            @trap();
        }
        @memcpy(self.buf[self.idx .. self.idx + s.len], s);
        self.idx += s.len;
    }
};

fn isShortcodeChar(ch: u8) bool {
    return std.ascii.isAlphanumeric(ch) or ch == '_' or ch == '+' or ch == '-';
}

fn renderImpl(input_size: u32) u32 {
    const input = input_buf[0..@as(usize, @intCast(input_size))];
    var w = Writer.init(output_buf[0..]);
    var i: usize = 0;
    while (i < input.len) {
        if (input[i] == ':') {
            const start = i;
            i += 1;
            var j = i;
            while (j < input.len and isShortcodeChar(input[j])) : (j += 1) {}
            if (j < input.len and input[j] == ':' and j > i) {
                const name = input[i..j];
                if (lookupEmoji(name)) |emoji| {
                    w.writeSlice(emoji);
                    i = j + 1;
                    continue;
                }
            }
            w.writeByte(':');
            i = start + 1;
            continue;
        }
        w.writeByte(input[i]);
        i += 1;
    }
    return @as(u32, @intCast(w.idx));
}

export fn render(input_size: u32) packed struct(u64) {
    output_size: u32,
    output_ptr: u31,
    failed: u1,
} {
    return .{
        .output_size = renderImpl(input_size),
        .output_ptr = @intCast(@intFromPtr(&output_buf)),
        .failed = 0,
    };
}

test "shortcode replace" {
    var out: [256]u8 = undefined;
    const input = "Hello :smile: world";
    const written = runString(input, out[0..]);
    try std.testing.expectEqualStrings("Hello 😄 world", out[0..written]);
}

test "unknown shortcode" {
    var out: [256]u8 = undefined;
    const input = "Hi :notreal: there";
    const written = runString(input, out[0..]);
    try std.testing.expectEqualStrings("Hi :notreal: there", out[0..written]);
}

test "custom emoji remains" {
    var out: [256]u8 = undefined;
    const input = "Ship :octocat:";
    const written = runString(input, out[0..]);
    try std.testing.expectEqualStrings("Ship :octocat:", out[0..written]);
}

fn runString(input: []const u8, out: []u8) usize {
    @memcpy(input_buf[0..input.len], input);
    const written = renderImpl(@as(u32, @intCast(input.len)));
    @memcpy(out[0..written], output_buf[0..written]);
    return @as(usize, @intCast(written));
}
